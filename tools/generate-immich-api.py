#!/usr/bin/env python3
"""Generate DarkRoom's Swift Immich API layer from Immich's OpenAPI spec.

    tools/generate-immich-api.py <immich-openapi-specs.json> <output-dir> <immich-version>

Writes:
  Models.swift      - Codable structs for every object schema, forward-compatible enums
  Operations.swift  - one async method per JSON operation on `ImmichClient`
  APIVersion.swift  - the Immich version the layer was generated from

Design notes
  * Required properties (per spec) are non-optional; everything else is optional.
  * Enums are RawRepresentable structs, so unknown values from newer servers never fail decoding.
  * Polymorphic / free-form values decode as `JSONValue`.
  * Binary/multipart/streaming endpoints are hand-written (see ImmichClient+Media.swift); they are
    emitted here only as `path` helpers.
"""
import json
import re
import sys

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init", "inout",
    "internal", "let", "open", "operator", "private", "protocol", "public", "rethrows", "static", "struct",
    "subscript", "typealias", "var", "break", "case", "continue", "default", "defer", "do", "else",
    "fallthrough", "for", "guard", "if", "in", "repeat", "return", "switch", "where", "while", "as", "Any",
    "catch", "false", "is", "nil", "super", "self", "Self", "throw", "throws", "true", "try", "Type",
}

spec_path, out_dir, version = sys.argv[1], sys.argv[2], sys.argv[3]
spec = json.load(open(spec_path))
schemas = spec["components"]["schemas"]


def ident(name):
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if name and name[0].isdigit():
        name = "_" + name
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def type_name(ref):
    return re.sub(r"[^A-Za-z0-9_]", "", ref.split("/")[-1])


def enum_case(value):
    v = re.sub(r"[^A-Za-z0-9]+", " ", str(value)).strip().split(" ")
    name = (v[0][:1].lower() + v[0][1:]) + "".join(p[:1].upper() + p[1:] for p in v[1:]) if v and v[0] else "empty"
    if name[0].isdigit():
        name = "_" + name
    return ident(name)


def swift_type(s):
    """Return (swift type, nullable) for a schema fragment."""
    if s is None:
        return "JSONValue", True
    if "$ref" in s:
        return type_name(s["$ref"]), False
    for key in ("anyOf", "oneOf", "allOf"):
        if key in s:
            options = s[key]
            non_null = [o for o in options if o.get("type") != "null"]
            nullable = len(non_null) != len(options) or s.get("nullable", False)
            if len(non_null) == 1:
                t, n = swift_type(non_null[0])
                return t, nullable or n
            return "JSONValue", nullable
    t = s.get("type")
    nullable = s.get("nullable", False)
    if isinstance(t, list):
        nullable = nullable or "null" in t
        t = next((x for x in t if x != "null"), None)
    if t == "string":
        return ("Data" if s.get("format") == "binary" else "String"), nullable
    if t == "integer":
        return "Int", nullable
    if t == "number":
        return "Double", nullable
    if t == "boolean":
        return "Bool", nullable
    if t == "array":
        inner, inner_nullable = swift_type(s.get("items"))
        return f"[{inner}{'?' if inner_nullable else ''}]", nullable
    if t == "object":
        if "properties" in s:
            return "JSONValue", nullable  # inline object
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            inner, _ = swift_type(ap)
            return f"[String: {inner}]", nullable
        return "JSONValue", nullable
    return "JSONValue", True


models = [
    "// Generated by tools/generate-immich-api.py - do not edit.",
    f"// Source: Immich {version} OpenAPI spec.",
    "",
    "import Foundation",
    "",
]

for name in sorted(schemas):
    s = schemas[name]
    tname = type_name(name)
    desc = (s.get("description") or "").replace("\n", " ")
    if "enum" in s:
        models.append(f"/// {desc}" if desc else f"/// {tname}")
        models.append(f"public struct {tname}: RawRepresentable, Codable, Hashable, Sendable, CustomStringConvertible {{")
        models.append("    public let rawValue: String")
        models.append("    public init(rawValue: String) { self.rawValue = rawValue }")
        models.append("    public init(_ rawValue: String) { self.rawValue = rawValue }")
        models.append("    public var description: String { rawValue }")
        seen = set()
        for v in s["enum"]:
            case = enum_case(v)
            if case in seen:
                continue
            seen.add(case)
            models.append(f'    public static let {case} = {tname}(rawValue: "{v}")')
        models.append(f"    public static let allKnown: [{tname}] = [{', '.join('.' + enum_case(v) for v in dict.fromkeys(s['enum']))}]")
        models.append("    public init(from decoder: Decoder) throws { rawValue = try decoder.singleValueContainer().decode(String.self) }")
        models.append("    public func encode(to encoder: Encoder) throws { var c = encoder.singleValueContainer(); try c.encode(rawValue) }")
        models.append("}")
        models.append("")
        continue
    if s.get("type") == "object" or "properties" in s:
        props = s.get("properties", {})
        required = set(s.get("required", []))
        models.append(f"/// {desc}" if desc else f"/// {tname}")
        models.append(f"public struct {tname}: Codable, Hashable, Sendable {{")
        fields = []
        for pname, p in props.items():
            t, nullable = swift_type(p)
            optional = nullable or pname not in required
            swift_name = ident(re.sub(r"[^A-Za-z0-9_]", "_", pname))
            pdesc = (p.get("description") or "").replace("\n", " ")
            if pdesc:
                models.append(f"    /// {pdesc}")
            models.append(f"    public var {swift_name}: {t}{'?' if optional else ''}")
            fields.append((pname, swift_name, t, optional))
        # memberwise init (public)
        params = ", ".join(f"{sn}: {t}{'? = nil' if opt else ''}" for _, sn, t, opt in fields)
        models.append(f"    public init({params}) {{")
        for _, sn, _, _ in fields:
            models.append(f"        self.{sn} = {sn}")
        models.append("    }")
        if any(pn != sn.strip("`") for pn, sn, _, _ in fields):
            models.append("    enum CodingKeys: String, CodingKey {")
            for pn, sn, _, _ in fields:
                models.append(f'        case {sn} = "{pn}"')
            models.append("    }")
        models.append("}")
        models.append("")
        continue
    t, _ = swift_type(s)
    models.append(f"public typealias {tname} = {t}")
    models.append("")

ops = [
    "// Generated by tools/generate-immich-api.py - do not edit.",
    f"// Source: Immich {version} OpenAPI spec.",
    "",
    "import Foundation",
    "",
    "public extension ImmichClient {",
]
skipped = []
for path, methods in sorted(spec["paths"].items()):
    for method, op in methods.items():
        if method not in ("get", "post", "put", "patch", "delete"):
            continue
        op_id = op.get("operationId")
        if not op_id:
            continue
        body = op.get("requestBody", {}).get("content", {})
        responses = op.get("responses", {})
        ok = next((responses[c] for c in ("200", "201", "204") if c in responses), {})
        rcontent = ok.get("content", {})
        if (body and "application/json" not in body) or (rcontent and "application/json" not in rcontent):
            skipped.append((op_id, method.upper(), path))
            continue
        params = op.get("parameters", [])
        path_params = [p for p in params if p.get("in") == "path"]
        query_params = [p for p in params if p.get("in") == "query"]
        sig = []
        for p in path_params:
            sig.append(f"{ident(p['name'])}: String")
        if body:
            bt, _ = swift_type(body["application/json"].get("schema"))
            sig.append(f"body: {bt}")
        for p in query_params:
            t, _ = swift_type(p.get("schema"))
            if t.startswith("["):
                t = "[String]" if "String" in t else t
            sig.append(f"{ident(p['name'])}: {t}{'' if p.get('required') else '? = nil'}")
        ret = "Void"
        if rcontent:
            ret, _ = swift_type(rcontent["application/json"].get("schema"))
        summary = (op.get("summary") or op.get("description") or "").replace("\n", " ")
        dep = " (deprecated)" if op.get("deprecated") else ""
        ops.append(f"    /// {method.upper()} {path}{dep} - {summary}")
        ops.append(f"    @discardableResult" if ret != "Void" else "")
        ops.append(f"    func {ident(op_id)}({', '.join(sig)}) async throws -> {ret} {{")
        swift_path = re.sub(r"\{([^}]+)\}", lambda m: "\\(" + ident(m.group(1)).strip("`") + ".pathEscaped)", path)
        ops.append(f'        var query: [URLQueryItem] = []')
        for p in query_params:
            n = ident(p["name"])
            raw = p["name"]
            t, _ = swift_type(p.get("schema"))
            if p.get("required"):
                ops.append(f'        query.append(contentsOf: QueryValue.items("{raw}", {n}))')
            else:
                ops.append(f'        if let {n} {{ query.append(contentsOf: QueryValue.items("{raw}", {n})) }}')
        body_arg = "body" if body else "Optional<Empty>.none"
        if ret == "Void":
            ops.append(f'        try await sendVoid("{method.upper()}", "{swift_path}", query: query, body: {body_arg})')
        else:
            ops.append(f'        return try await send("{method.upper()}", "{swift_path}", query: query, body: {body_arg})')
        ops.append("    }")
ops.append("}")
ops.append("")
ops.append("/// Endpoints with binary, multipart or streaming bodies; implemented by hand in ImmichClient+Media.swift.")
ops.append("public enum HandWrittenEndpoints {")
for op_id, m, p in skipped:
    ops.append(f'    public static let {ident(op_id)} = "{m} {p}"')
ops.append("}")

open(f"{out_dir}/Models.swift", "w").write("\n".join(models) + "\n")
open(f"{out_dir}/Operations.swift", "w").write("\n".join(l for l in ops if l != "") + "\n")
open(f"{out_dir}/APIVersion.swift", "w").write(
    "// Generated by tools/generate-immich-api.py - do not edit.\n\n"
    f'public enum ImmichAPIVersion {{\n    /// Immich release this API layer was generated from.\n    public static let generatedFrom = "{version}"\n}}\n')
print(f"models: {len(schemas)}  operations: {sum(1 for l in ops if l.strip().startswith('func '))}  hand-written: {len(skipped)}")
